export function categoryOf(tx) {
  return store.categoryById(tx.categoryId);
}

export function subcategoryOf(tx) {
  return tx.subcategoryId ? store.subcategoryById(tx.categoryId, tx.subcategoryId) : null;
}

export function txTitle(tx) {
  if (tx.type === 'transfer') return tx.note || 'Transfer antar akun';
  const category = categoryOf(tx);
  const sub = subcategoryOf(tx);
  return tx.note || sub?.name || category?.name || 'Transaksi';
}

export function txSubtitle(tx) {
  if (tx.type === 'transfer') {
    return `${store.accountName(tx.accountId)} → ${store.accountName(tx.toAccountId)}`;
  }
  const category = categoryOf(tx);
  const sub = subcategoryOf(tx);
  const parts = [];
  if (category && sub) parts.push(`${category.name} · ${sub.name}`);
  else if (category) parts.push(category.name);
  parts.push(store.accountName(tx.accountId));
  return parts.join(' · ');
}

export function typeIcon(type) {
  return TX_TYPES[type]?.icon || 'receipt';
}

export function typeBadge(type) {
  const item = TX_TYPES[type] || TX_TYPES.expense;
  const tone = type === 'income' ? 'green' : type === 'transfer' ? 'blue' : 'red';
  return badge(escapeHTML(item.short), tone);
}

export function accountIcon(account) {
  return ACCOUNT_TYPES[account?.type]?.icon || 'wallet';
}

export function txRow(tx, { showDate = false, showCreator = true, compact = false } = {}) {
  const type = TX_TYPES[tx.type] || TX_TYPES.expense;
  const category = categoryOf(tx);
  const account = store.accountById(tx.accountId);
  const creator = store.getUser(tx.createdBy);
  const color = tx.type === 'transfer' ? '#3B82F6' : category?.color || type.color;
  const iconName = tx.type === 'transfer' ? 'arrow-left-right' : category?.icon || type.icon;
  const amountClass = tx.type === 'income' ? 'amount-income' : tx.type === 'expense' ? 'amount-expense' : 'amount-transfer';
  const sign = tx.type === 'income' ? '+' : tx.type === 'expense' ? '-' : '';
  return `<button type="button" class="tx-row ${compact ? 'tx-row-compact' : ''}" data-action="edit-tx" data-id="${escapeAttr(tx.id)}">
    <span class="tx-icon" style="--tx-color:${escapeAttr(color)}">${icon(iconName, 'w-4.5 h-4.5')}</span>
    <span class="tx-main">
      <span class="tx-title-line">
        <span class="tx-title">${escapeHTML(txTitle(tx))}</span>
        ${tx.autoGenerated ? `<span class="tx-repeat" title="Dibuat otomatis">${icon('repeat', 'w-3 h-3')}</span>` : ''}
      </span>
      <span class="tx-meta">
        ${showDate ? `<span>${escapeHTML(formatDate(tx.date))}</span>` : ''}
        <span>${escapeHTML(txSubtitle(tx))}</span>
        ${showCreator ? `<span class="tx-creator" style="--creator-color:${escapeAttr(creator?.color || '#64748B')}">${escapeHTML(tx.createdByName || creator?.name || '—')}</span>` : ''}
      </span>
    </span>
    <span class="tx-side">
      <span class="tx-amount ${amountClass}">${sign}${money(tx.amount)}</span>
      ${!compact && account ? `<span class="tx-account-dot" style="--dot-color:${escapeAttr(account.color || '#64748B')}">${escapeHTML(account.name)}</span>` : ''}
    </span>
  </button>`;
}

export function transactionDayGroups(transactions) {
  const groups = new Map();
  transactions.forEach((tx) => {
    if (!groups.has(tx.date)) groups.set(tx.date, []);
    groups.get(tx.date).push(tx);
  });
  return [...groups.entries()].map(([date, items]) => {
    const summary = store.summaryForTransactions(items);
    return { date, items, summary };
  });
}

export function dayGroupHeader(date, summary) {
  const today = todayISO();
  const label = date === today ? 'Hari ini' : relativeDay(date);
  return `<div class="day-group-head">
    <div>
      <span class="day-group-label">${escapeHTML(label)}</span>
      <span class="day-group-date">${escapeHTML(formatDate(date, { weekday: 'short', day: 'numeric', month: 'long', year: 'numeric' }))}</span>
    </div>
    <div class="day-group-totals">
      ${summary.income ? `<span class="amount-income">+${money(summary.income)}</span>` : ''}
      ${summary.expense ? `<span class="amount-expense">-${money(summary.expense)}</span>` : ''}
    </div>
  </div>`;
}

export function monthNav(month, actionPrev = 'month-prev', actionNext = 'month-next', target = '') {
  return `<div class="month-nav">
    <button type="button" class="icon-btn" data-action="${actionPrev}" ${target ? `data-target="${target}"` : ''} aria-label="Bulan sebelumnya">${icon('chevron-left')}</button>
    <div class="month-nav-label">${escapeHTML(formatMonth(month))}</div>
    <button type="button" class="icon-btn" data-action="${actionNext}" ${target ? `data-target="${target}"` : ''} aria-label="Bulan berikutnya">${icon('chevron-right')}</button>
  </div>`;
}

export function dueDateBadge(dueDate, done = false) {
  if (!dueDate) return '';
  const today = todayISO();
  if (done) return badge('Selesai', 'green', 'badge-soft');
  if (dueDate < today) return badge(`Terlambat · ${formatDate(dueDate)}`, 'red', 'badge-soft');
  if (dueDate === today) return badge('Hari ini', 'amber', 'badge-soft');
  const label = relativeDay(dueDate);
  return badge(label, 'slate', 'badge-soft');
}

export function priorityBadge(priority) {
  const item = PRIORITIES[priority] || PRIORITIES.normal;
  const tone = priority === 'urgent' ? 'red' : priority === 'high' ? 'amber' : priority === 'low' ? 'slate' : 'blue';
  return badge(escapeHTML(item.label), tone, 'badge-soft');
}

export function noteCompletion(note) {
  if (!note.items?.length) return { total: 0, done: note.done ? 1 : 0, percent: note.done ? 100 : 0 };
  const done = note.items.filter((item) => item.done).length;
  return { total: note.items.length, done, percent: (done / note.items.length) * 100 };
}

export function noteCard(note, { view = 'grid', action = 'edit-note' } = {}) {
  const color = NOTE_COLORS[note.color] || NOTE_COLORS.yellow;
  const tags = (note.tags || []).slice(0, 4).map((tag) => `<span class="note-tag">#${escapeHTML(tag)}</span>`).join('');
  const completion = noteCompletion(note);
  const isTrashed = note.status === 'trashed';
  const isArchived = note.status === 'archived';
  const kindIcon = note.kind === 'todo' ? 'check-square' : 'sticky-note';
  const due = note.kind === 'todo' ? dueDateBadge(note.dueDate, note.done) : '';
  const preview = note.kind === 'note'
    ? (plainTextPreview(note.content, 260) ? escapeHTML(plainTextPreview(note.content, 260)) : '<span class="text-slate-400">Catatan kosong</span>')
    : (note.content ? escapeHTML(plainTextPreview(note.content, 180)) : '');
  const checked = note.done ? 'is-done' : '';
  const quickCheck = note.kind === 'todo'
    ? `<button type="button" class="todo-check ${checked}" data-action="todo-toggle" data-id="${escapeAttr(note.id)}" aria-label="${note.done ? 'Tandai belum selesai' : 'Tandai selesai'}">${note.done ? icon('check', 'w-3.5 h-3.5') : ''}</button>`
    : `<span class="note-kind-icon">${icon(kindIcon, 'w-4 h-4')}</span>`;

  const itemRows = note.kind === 'todo' && note.items?.length
    ? `<div class="todo-preview-list">
      ${note.items.slice(0, 4).map((item) => `<button type="button" class="todo-preview-item ${item.done ? 'is-done' : ''}" data-action="todo-item-toggle" data-note="${escapeAttr(note.id)}" data-item="${escapeAttr(item.id)}">
        <span class="mini-check ${item.done ? 'is-done' : ''}">${item.done ? icon('check', 'w-2.5 h-2.5') : ''}</span>
        <span>${escapeHTML(item.text)}</span>
      </button>`).join('')}
      ${note.items.length > 4 ? `<span class="todo-more">+${note.items.length - 4} item lainnya</span>` : ''}
    </div>`
    : '';

  const actions = isTrashed
    ? `<div class="note-card-actions">
      <button type="button" class="card-icon-btn" data-action="note-restore" data-id="${escapeAttr(note.id)}" title="Pulihkan">${icon('rotate-ccw', 'w-3.5 h-3.5')}</button>
      <button type="button" class="card-icon-btn danger" data-action="note-purge" data-id="${escapeAttr(note.id)}" title="Hapus permanen">${icon('trash', 'w-3.5 h-3.5')}</button>
    </div>`
    : `<div class="note-card-actions">
      ${!isArchived ? `<button type="button" class="card-icon-btn ${note.pinned ? 'active' : ''}" data-action="note-pin" data-id="${escapeAttr(note.id)}" title="${note.pinned ? 'Lepas pin' : 'Sematkan'}">${icon('pin', 'w-3.5 h-3.5')}</button>` : ''}
      <button type="button" class="card-icon-btn" data-action="note-archive" data-id="${escapeAttr(note.id)}" title="${isArchived ? 'Aktifkan kembali' : 'Arsipkan'}">${icon(isArchived ? 'rotate-ccw' : 'archive', 'w-3.5 h-3.5')}</button>
      ${!isArchived ? `<button type="button" class="card-icon-btn" data-action="note-trash" data-id="${escapeAttr(note.id)}" title="Pindahkan ke sampah">${icon('trash', 'w-3.5 h-3.5')}</button>` : ''}
    </div>`;

  return `<article class="note-card ${view === 'list' ? 'note-card-list' : ''} ${isTrashed ? 'is-trashed' : ''} ${isArchived ? 'is-archived' : ''}" data-color="${escapeAttr(note.color)}" style="--note-bg:${escapeAttr(color.bg)};--note-border:${escapeAttr(color.border)};--note-ink:${escapeAttr(color.ink)}">
    <div class="note-card-top">
      ${quickCheck}
      <button type="button" class="note-card-title-wrap" data-action="${isTrashed ? 'note-restore' : action}" data-id="${escapeAttr(note.id)}">
        <span class="note-title ${note.done ? 'line-through opacity-60' : ''}">${escapeHTML(note.title)}</span>
        <span class="note-subline">
          ${note.pinned ? icon('pin', 'w-3 h-3 inline -mt-0.5') : ''}
          ${note.favorite ? icon('star', 'w-3 h-3 inline -mt-0.5') : ''}
          <span>${escapeHTML(note.kind === 'todo' ? 'Tugas' : 'Catatan')}</span>
          ${note.kind === 'todo' && completion.total ? `<span>· ${completion.done}/${completion.total}</span>` : ''}
        </span>
      </button>
      ${actions}
    </div>
    ${note.kind === 'note'
      ? `<button type="button" class="note-preview" data-action="${isTrashed ? 'note-restore' : action}" data-id="${escapeAttr(note.id)}">${preview}</button>`
      : `<div class="note-preview todo-preview">
          ${preview ? `<p>${preview}</p>` : ''}
          ${completion.total ? `<div class="todo-progress">${progressBar(completion.percent, completion.percent >= 100 ? 'safe' : 'info', 'progress-thin')}<span>${Math.round(completion.percent)}%</span></div>` : ''}
          ${itemRows}
        </div>`}
    <div class="note-card-bottom">
      <div class="note-badges">${due}${note.kind === 'todo' ? priorityBadge(note.priority) : ''}</div>
      <div class="note-tags">${tags}</div>
    </div>
    <div class="note-footer">
      <span>${escapeHTML(note.createdByName || '—')}</span>
      <span>${escapeHTML(timeAgo(note.updatedAt))}</span>
    </div>
  </article>`;
}

export function recurringRow(rule, { embedded = false } = {}) {
  const type = TX_TYPES[rule.type] || TX_TYPES.expense;
  const account = store.accountById(rule.accountId);
  const category = store.categoryById(rule.categoryId);
  const due = rule.nextDate <= todayISO();
  const freq = FREQUENCIES[rule.frequency] || FREQUENCIES.monthly;
  return `<div class="recurring-row ${!rule.active ? 'is-paused' : ''}">
    <span class="tx-icon" style="--tx-color:${escapeAttr(category?.color || type.color)}">${icon(rule.type === 'transfer' ? 'repeat' : category?.icon || type.icon, 'w-4.5 h-4.5')}</span>
    <div class="recurring-main">
      <div class="flex items-center gap-2 flex-wrap">
        <span class="font-semibold text-sm text-slate-900 dark:text-white">${escapeHTML(rule.title)}</span>
        ${due && rule.active ? badge('Jatuh tempo', 'amber', 'badge-soft') : ''}
        ${!rule.active ? badge('Dijeda', 'slate', 'badge-soft') : ''}
        ${!rule.autoPost ? badge('Manual', 'purple', 'badge-soft') : ''}
      </div>
      <div class="text-xs text-slate-500 dark:text-slate-400 mt-1">
        ${escapeHTML(rule.type === 'transfer' ? `${store.accountName(rule.accountId)} → ${store.accountName(rule.toAccountId)}` : `${account?.name || '—'}${category ? ` · ${escapeHTML(category.name)}` : ''}`)}
        · ${escapeHTML(freq.label)} ${rule.interval > 1 ? `tiap ${rule.interval} ${escapeHTML(freq.adverb)}` : ''}
      </div>
      <div class="text-xs text-slate-500 dark:text-slate-400 mt-0.5">Berikutnya ${escapeHTML(formatDate(rule.nextDate))}${rule.autoPost ? '' : ' · posting manual'}</div>
    </div>
    <div class="recurring-side">
      <span class="tx-amount ${rule.type === 'income' ? 'amount-income' : rule.type === 'expense' ? 'amount-expense' : 'amount-transfer'}">${money(rule.amount)}</span>
      <div class="recurring-actions">
        <button type="button" class="card-icon-btn" data-action="toggle-rec" data-id="${escapeAttr(rule.id)}" title="${rule.active ? 'Jeda' : 'Aktifkan'}">${icon(rule.active ? 'pause' : 'play', 'w-3.5 h-3.5')}</button>
        ${due ? `<button type="button" class="card-icon-btn" data-action="post-rec" data-id="${escapeAttr(rule.id)}" title="Posting sekarang">${icon('plus', 'w-3.5 h-3.5')}</button>` : ''}
        <button type="button" class="card-icon-btn" data-action="edit-rec" data-id="${escapeAttr(rule.id)}" title="Ubah">${icon('edit', 'w-3.5 h-3.5')}</button>
        <button type="button" class="card-icon-btn danger" data-action="delete-rec" data-id="${escapeAttr(rule.id)}" title="Hapus">${icon('trash', 'w-3.5 h-3.5')}</button>
      </div>
    </div>
  </div>`;
}

export function categoryChip(category, subcategory = null) {
  if (!category) return '';
  return `<span class="category-chip" style="--chip-color:${escapeAttr(category.color || '#64748B')}">${icon(category.icon || 'tag', 'w-3 h-3')}${escapeHTML(category.name)}${subcategory ? ` · ${escapeHTML(subcategory.name)}` : ''}</span>`;
}

export function statCard({ label, value, iconName, tone = 'blue', hint = '', action = '' }) {
  return `<div class="stat-card stat-${tone}" ${action ? `data-action="${action}"` : ''}>
    <div class="stat-top"><span>${escapeHTML(label)}</span><span class="stat-icon">${icon(iconName, 'w-4 h-4')}</span></div>
    <div class="stat-value">${value}</div>
    ${hint ? `<div class="stat-hint">${hint}</div>` : ''}
  </div>`;
}

export function insightBar(label, value, total, tone = 'info') {
  const percent = total > 0 ? (value / total) * 100 : 0;
  return `<div class="insight-row">
    <div class="insight-label"><span>${escapeHTML(label)}</span><span>${money(value)}</span></div>
    ${progressBar(percent, tone, 'progress-thin')}
    <div class="insight-percent">${formatPercent(percent, 1)}</div>
  </div>`;
}

export function budgetTone(percent, warning = 75, danger = 90) {
  return toneForPercent(percent, warning, danger);
}
